import { expect, test, type APIRequestContext } from '@playwright/test'

async function create(request: APIRequestContext, path: string, data: unknown) {
  const response = await request.post(`/api/v1/${path}`, { data })
  expect(response.ok()).toBeTruthy()
  return response.json()
}
function month(offset: number) {
  const now = new Date()
  const date = new Date(now.getFullYear(), now.getMonth() + offset, 1)
  return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}`
}

test('closing a liability requires an explicit zero, preserves history, and can be reopened', async ({ page, request }) => {
  const suffix = Date.now()
  const person = await create(request, 'persons', { name: `Closure person ${suffix}` })
  const category = await create(request, 'categories', { name: `Closure debt ${suffix}`, type: 'liability', projected_yearly_growth: -0.05, color: '#f43f5e' })
  const asset = await create(request, 'assets', { name: `Closure liability ${suffix}`, category_id: category.id, person_id: person.id, projected_yearly_growth: -0.01, include_in_current_wealth: true, include_in_projections: true, notes: 'Retain synthetic note' })
  await create(request, 'data-points', { asset_id: asset.id, year_month: month(-2), value: -500 })
  await page.goto('/admin')
  await page.getByRole('tab', { name: 'Liabilities' }).click()
  await page.getByRole('button', { name: `Edit asset ${asset.name}` }).click()
  let dialog = page.getByRole('dialog', { name: 'Edit Liability' })
  await dialog.getByText('Advanced', { exact: true }).click()
  const closed = dialog.getByRole('checkbox', { name: 'Closed', exact: true })
  await expect(closed).not.toBeChecked()
  await closed.check()
  const closing = dialog.getByLabel('Closing month')
  await expect(closing).toHaveValue(month(0))
  await expect(dialog.getByText(/Record a final zero value/)).toBeVisible()
  await closing.fill('')
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Closing month is required')
  await closing.fill(month(-1))
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog.getByRole('alert')).toContainText(/zero/i)
  const before = await (await request.get(`/api/v1/data-points?asset_id=${asset.id}`)).json()
  expect(before.some((point: { year_month: string }) => point.year_month === month(-1))).toBe(false)
  await create(request, 'data-points', { asset_id: asset.id, year_month: month(-1), value: 0 })
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  const row = page.getByRole('row').filter({ hasText: asset.name })
  await expect(row.getByText(`Closed ${month(-1)}`)).toBeVisible()
  const stored = (await (await request.get('/api/v1/assets')).json()).find((item: { id: string }) => item.id === asset.id)
  expect(stored.closed_at).toBe(month(-1))
  const summary = await (await request.get(`/api/v1/summary?range=1y&person=${person.id}`)).json()
  expect(summary.asset_breakdown.some((item: { asset_id: string }) => item.asset_id === asset.id)).toBe(false)
  const projection = await (await request.get('/api/v1/projections?years=5&scenario=base')).json()
  expect(projection.projection.asset_metadata.some((item: { asset_id: string }) => item.asset_id === asset.id)).toBe(false)

  await page.goto(`/monthly-update?month=${month(-1)}&person=${person.id}`)
  await expect(page.getByRole('spinbutton', { name: new RegExp(`Value for ${asset.name} in ${month(-1)}`) }).last()).toHaveValue('0')
  await page.goto(`/monthly-update?month=${month(0)}&person=${person.id}`)
  await expect(page.getByRole('spinbutton', { name: new RegExp(`Value for ${asset.name}`) })).toHaveCount(0)
  await page.goto('/projections')
  await expect(page.locator('#assumptions-panel').getByText(asset.name, { exact: true })).toHaveCount(0)
  await page.goto('/data-points')
  await page.getByRole('combobox', { name: 'Filter by asset' }).click()
  await page.getByRole('option', { name: asset.name, exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: asset.name })).toHaveCount(2)

  await page.goto('/admin')
  await page.getByRole('tab', { name: 'Liabilities' }).click()
  await page.getByRole('button', { name: `Edit asset ${asset.name}` }).click()
  dialog = page.getByRole('dialog', { name: 'Edit Liability' })
  await dialog.getByText('Advanced', { exact: true }).click()
  await expect(dialog.getByLabel('Closing month')).toHaveValue(month(-1))
  await dialog.getByRole('checkbox', { name: 'Closed', exact: true }).uncheck()
  await expect(dialog.getByLabel('Closing month')).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  const reopened = (await (await request.get('/api/v1/assets')).json()).find((item: { id: string }) => item.id === asset.id)
  expect(reopened.closed_at ?? null).toBeNull()
  expect(reopened.projected_yearly_growth).toBe(-0.01)
  expect(reopened.include_in_current_wealth).toBe(true)
  expect(reopened.include_in_projections).toBe(true)
  expect(reopened.notes).toBe('Retain synthetic note')
  await page.goto(`/monthly-update?month=${month(0)}&person=${person.id}`)
  await expect(page.getByRole('spinbutton', { name: new RegExp(`Value for ${asset.name}`) }).last()).toBeVisible()
  const reopenedSummary = await (await request.get(`/api/v1/summary?range=1y&person=${person.id}`)).json()
  expect(reopenedSummary.total_liabilities).toBe(0)
})

test('future closure remains active through its month and income may close with nonzero value', async ({ page, request }) => {
  const suffix = Date.now()
  const person = await create(request, 'persons', { name: `Scheduled closure person ${suffix}` })
  const category = await create(request, 'categories', { name: `Scheduled asset category ${suffix}`, type: 'asset', projected_yearly_growth: 0, color: '#6366f1' })
  const incomeCategory = await create(request, 'categories', { name: `Closed income category ${suffix}`, type: 'cash-inflow', projected_yearly_growth: 0, color: '#14b8a6' })
  const asset = await create(request, 'assets', { name: `Scheduled asset ${suffix}`, category_id: category.id, person_id: person.id, projected_yearly_growth: null })
  const income = await create(request, 'assets', { name: `Closed income ${suffix}`, category_id: incomeCategory.id, person_id: person.id, projected_yearly_growth: null })
  await create(request, 'data-points/batch', { items: [
    { asset_id: asset.id, year_month: month(0), value: 100 },
    { asset_id: asset.id, year_month: month(1), value: 0 },
    { asset_id: income.id, year_month: month(0), value: 200 },
  ] })
  await page.goto('/admin')
  await page.getByRole('tab', { name: 'Assets', exact: false }).click()
  await page.getByRole('button', { name: `Edit asset ${asset.name}` }).click()
  let dialog = page.getByRole('dialog', { name: 'Edit Asset' })
  await dialog.getByText('Advanced', { exact: true }).click()
  await dialog.getByRole('checkbox', { name: 'Closed', exact: true }).check()
  await dialog.getByLabel('Closing month').fill(month(1))
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('row').filter({ hasText: asset.name }).getByText(`Closes after ${month(1)}`)).toBeVisible()
  await page.goto(`/monthly-update?month=${month(1)}&person=${person.id}`)
  await expect(page.getByRole('spinbutton', { name: new RegExp(`Value for ${asset.name}`) }).last()).toBeVisible()
  await page.goto(`/monthly-update?month=${month(2)}&person=${person.id}`)
  await expect(page.getByRole('spinbutton', { name: new RegExp(`Value for ${asset.name}`) })).toHaveCount(0)
  await page.goto('/projections')
  await expect(page.locator('#assumptions-panel').getByText(asset.name, { exact: true })).toHaveCount(1)
  const forecast = await (await request.get('/api/v1/projections?years=5&scenario=base')).json()
  const series = forecast.projection.series.find((item: { category_id: string }) => item.category_id === category.id)
  expect(series.available.slice(0, 2)).toEqual([true, false])
  expect(series.values.slice(0, 2)).toEqual([0, 0])
  await page.goto('/admin')
  await page.getByRole('tab', { name: 'Income', exact: false }).click()
  await page.getByRole('button', { name: `Edit asset ${income.name}` }).click()
  dialog = page.getByRole('dialog', { name: 'Edit Income' })
  await dialog.getByText('Advanced', { exact: true }).click()
  await dialog.getByRole('checkbox', { name: 'Closed', exact: true }).check()
  await expect(dialog.getByText(/Record a final zero value/)).toHaveCount(0)
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  const stored = (await (await request.get('/api/v1/assets')).json()).find((item: { id: string }) => item.id === income.id)
  expect(stored.closed_at).toBe(month(0))
})

test('a closed-only portfolio keeps its payoff change and historical dashboard values', async ({ page, request }) => {
  const suffix = Date.now()
  const person = await create(request, 'persons', { name: `Paid portfolio ${suffix}` })
  const category = await create(request, 'categories', { name: `Paid debt ${suffix}`, type: 'liability', projected_yearly_growth: 0, color: '#f43f5e' })
  const asset = await create(request, 'assets', { name: `Paid loan ${suffix}`, category_id: category.id, person_id: person.id, projected_yearly_growth: null })
  await create(request, 'data-points/batch', { items: [
    { asset_id: asset.id, year_month: month(-2), value: -500 },
    { asset_id: asset.id, year_month: month(-1), value: 0 },
  ] })
  expect((await request.put(`/api/v1/assets/${asset.id}`, { data: {
    name: asset.name, category_id: category.id, person_id: person.id,
    projected_yearly_growth: null, closed_at: month(-1),
  } })).ok()).toBeTruthy()
  const summary = await (await request.get(`/api/v1/summary?range=1y&person=${person.id}`)).json()
  expect(summary.current_total).toBe(0)
  expect(summary.period_delta_available).toBe(true)
  expect(summary.period_delta_abs).toBe(500)
  expect(summary.period_start_month).toBe(month(-2))
  expect(summary.asset_breakdown).toHaveLength(0)
  expect(summary.monthly_coverage.total).toBe(0)
  await page.goto('/')
  await page.getByRole('button', { name: person.name, exact: true }).click()
  await page.getByRole('button', { name: '1Y', exact: true }).click()
  await expect(page.getByText('No active items to display', { exact: true })).toBeVisible()
  await expect(page.getByText('No data to display', { exact: true })).toHaveCount(0)
  const period = page.getByText('Period Change', { exact: true }).locator('..')
  await expect(period).toContainText('+500,00')
  await expect(period).toContainText(`Since ${month(-2)}`)
  await expect(page.getByRole('link', { name: 'Monthly completion: 0/0 observed', exact: true })).toBeVisible()
  await page.getByText('View wealth trends data', { exact: true }).click()
  const table = page.getByRole('table', { name: 'wealth trends values by month', exact: true })
  const past = table.getByRole('row').filter({ has: page.getByRole('rowheader', { name: month(-2), exact: true }) })
  await expect(past).toContainText('-500,00')
})
