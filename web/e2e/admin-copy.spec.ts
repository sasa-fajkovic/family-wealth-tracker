import { expect, test, type APIRequestContext } from '@playwright/test'

async function create(request: APIRequestContext, path: string, data: unknown) {
  const response = await request.post(`/api/v1/${path}`, { data })
  expect(response.ok()).toBeTruthy()
  return response.json()
}

test('monthly earlier recorded value can precede the previous calendar month and copying remains unsaved', async ({ page, request }) => {
  const suffix = Date.now()
  const person = await create(request, 'persons', { name: `Copy person ${suffix}` })
  const category = await create(request, 'categories', { name: `Copy category ${suffix}`, type: 'asset', projected_yearly_growth: 0, color: '#6366f1' })
  const asset = await create(request, 'assets', { name: `Copy item ${suffix}`, person_id: person.id, category_id: category.id, projected_yearly_growth: null })
  await create(request, 'data-points', { asset_id: asset.id, year_month: '2024-01', value: 123 })

  await page.goto(`/monthly-update?month=2024-04&person=${person.id}`)
  await expect(page.getByRole('columnheader', { name: 'Earlier recorded value', exact: true })).toBeVisible()
  const row = page.locator('table').getByRole('row').filter({ hasText: asset.name })
  await expect(row).toContainText('2024-01')
  await expect(row).toContainText('123,00')
  await expect(row).toContainText('No entry')
  const input = row.getByRole('spinbutton')
  await expect(input).toHaveValue('')
  await page.getByRole('button', { name: 'Copy earlier values', exact: true }).click()
  await expect(input).toHaveValue('123')
  await expect(row).toContainText('Unsaved')
  await page.setViewportSize({ width: 390, height: 844 })
  const card = page.locator('div[data-testid="monthly-row"]').filter({ hasText: asset.name })
  await expect(card).toContainText('Earlier recorded value')
  await expect(card).toContainText('2024-01')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  const points = await (await request.get(`/api/v1/data-points?asset_id=${asset.id}`)).json()
  expect(points).toHaveLength(1)
  expect(points[0].year_month).toBe('2024-01')
})

test('admin distinguishes annual debt assumptions, unused income rates, and monthly entry visibility', async ({ page, request }) => {
  const suffix = Date.now()
  const person = await create(request, 'persons', { name: `Copy admin person ${suffix}` })
  const debt = await create(request, 'categories', { name: `Copy debt ${suffix}`, type: 'liability', projected_yearly_growth: -0.05, color: '#f43f5e' })
  const income = await create(request, 'categories', { name: `Copy income ${suffix}`, type: 'cash-inflow', projected_yearly_growth: 0.08, color: '#14b8a6' })
  const loan = await create(request, 'assets', { name: `Copy loan ${suffix}`, person_id: person.id, category_id: debt.id, projected_yearly_growth: null })
  const salary = await create(request, 'assets', { name: `Copy salary ${suffix}`, person_id: person.id, category_id: income.id, projected_yearly_growth: null })
  await page.goto('/admin')
  await page.getByRole('tab', { name: /Liabilities/ }).click()
  await expect(page.getByRole('columnheader', { name: 'Annual projection rate (%)', exact: true })).toBeVisible()
  await page.getByRole('button', { name: `Edit liability ${loan.name}`, exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Edit Liability', exact: true })
  await expect(dialog.getByText(/a negative rate assumes it shrinks annually/)).toBeVisible()
  await expect(dialog.getByText(/These dates only control which months show this item in Monthly Update/)).toBeVisible()
  await dialog.getByText('Advanced', { exact: true }).click()
  await expect(dialog.getByText(/Current wealth inclusion also applies to historical wealth totals/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('tab', { name: /Income/ }).click()
  await expect(page.getByRole('row').filter({ hasText: salary.name })).toContainText('Not used for income')
  await page.getByRole('button', { name: `Edit income ${salary.name}`, exact: true }).click()
  await expect(page.getByRole('dialog').getByText(/This rate is stored but unused for income/)).toBeVisible()
  const stored = (await (await request.get('/api/v1/categories')).json()).find((item: { id: string }) => item.id === income.id)
  expect(stored.projected_yearly_growth).toBe(0.08)
})
