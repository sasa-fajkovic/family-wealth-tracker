import { expect, test, type APIRequestContext } from '@playwright/test'

async function create(request: APIRequestContext, path: string, data: unknown) {
  const response = await request.post(`/api/v1/${path}`, { data })
  expect(response.ok()).toBeTruthy()
  return response.json()
}

test('category defaults and asset overrides control current wealth and planned projections', async ({ page, request }) => {
  const suffix = Date.now()
  const person = await create(request, 'persons', { name: `Inclusion person ${suffix}` })
  await page.goto('/admin')
  await page.getByRole('tab', { name: 'Categories' }).click()
  await page.getByRole('button', { name: 'Add Category' }).click()
  let dialog = page.getByRole('dialog', { name: 'Add Category' })
  const categoryName = `Inclusion category ${suffix}`
  await dialog.getByRole('textbox').first().fill(categoryName)
  await dialog.getByRole('spinbutton').fill('5')
  const currentSwitch = dialog.getByRole('switch', { name: 'Include in current wealth' })
  const projectionSwitch = dialog.getByRole('switch', { name: 'Include in projections' })
  await expect(currentSwitch).toBeChecked()
  await expect(projectionSwitch).toBeChecked()
  const timingHint = 'Uses future-dated values in projections; current estimates are excluded.'
  await expect(dialog.getByText(timingHint, { exact: true })).toHaveCount(0)
  await currentSwitch.click()
  await expect(dialog.getByText(timingHint, { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText(categoryName, { exact: true })).toBeVisible()
  const categories = await (await request.get('/api/v1/categories')).json()
  const category = categories.find((item: { name: string }) => item.name === categoryName)
  expect(category.include_in_current_wealth).toBe(false)
  expect(category.include_in_projections).toBe(true)

  await page.getByRole('tab', { name: 'Assets' }).click()
  await page.getByRole('button', { name: 'Add Asset' }).click()
  dialog = page.getByRole('dialog', { name: 'Add Asset' })
  const plannedName = `Future planned ${suffix}`
  await dialog.getByRole('textbox').first().fill(plannedName)
  await dialog.getByRole('combobox').nth(0).click()
  await page.getByRole('option', { name: categoryName, exact: true }).click()
  await dialog.getByRole('combobox').nth(1).click()
  await page.getByRole('option', { name: person.name, exact: true }).click()
  await dialog.getByText('Advanced', { exact: true }).click()
  let current = dialog.getByRole('group', { name: 'Current wealth', exact: true })
  let projected = dialog.getByRole('group', { name: 'Projections', exact: true })
  await expect(current.getByRole('radio', { name: 'Inherit (excluded)' })).toBeChecked()
  await expect(projected.getByRole('radio', { name: 'Inherit (included)' })).toBeChecked()
  await expect(dialog.getByText(timingHint, { exact: true })).toBeVisible()
  await expect(dialog.getByRole('radio')).toHaveCount(6)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  for (const radio of await dialog.getByRole('radio').all()) {
    const box = await radio.boundingBox()
    expect(box!.x).toBeGreaterThanOrEqual(0)
    expect(box!.x + box!.width).toBeLessThanOrEqual(390)
  }
  await page.setViewportSize({ width: 1280, height: 720 })
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(page.getByText(plannedName, { exact: true })).toBeVisible()
  const assets = await (await request.get('/api/v1/assets')).json()
  const planned = assets.find((item: { name: string }) => item.name === plannedName)
  expect(planned.include_in_current_wealth ?? null).toBeNull()
  expect(planned.include_in_projections ?? null).toBeNull()

  await page.getByRole('button', { name: `Edit asset ${plannedName}` }).click()
  dialog = page.getByRole('dialog', { name: 'Edit Asset' })
  await dialog.getByText('Advanced', { exact: true }).click()
  current = dialog.getByRole('group', { name: 'Current wealth', exact: true })
  projected = dialog.getByRole('group', { name: 'Projections', exact: true })
  await current.getByRole('radio', { name: 'Include', exact: true }).check()
  await expect(dialog.getByText(timingHint, { exact: true })).toHaveCount(0)
  await projected.getByRole('radio', { name: 'Exclude', exact: true }).check()
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  let updated = (await (await request.get('/api/v1/assets')).json()).find((item: { id: string }) => item.id === planned.id)
  expect(updated.include_in_current_wealth).toBe(true)
  expect(updated.include_in_projections).toBe(false)
  await page.getByRole('button', { name: `Edit asset ${plannedName}` }).click()
  dialog = page.getByRole('dialog', { name: 'Edit Asset' })
  await dialog.getByText('Advanced', { exact: true }).click()
  await dialog.getByRole('group', { name: 'Current wealth' }).getByRole('radio', { name: 'Inherit (excluded)' }).check()
  await dialog.getByRole('group', { name: 'Projections' }).getByRole('radio', { name: 'Inherit (included)' }).check()
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  updated = (await (await request.get('/api/v1/assets')).json()).find((item: { id: string }) => item.id === planned.id)
  expect(updated.include_in_current_wealth ?? null).toBeNull()
  expect(updated.include_in_projections ?? null).toBeNull()

  const actualOnly = await create(request, 'assets', { name: `Actual only ${suffix}`, category_id: category.id, person_id: person.id, projected_yearly_growth: null, include_in_current_wealth: true, include_in_projections: false })
  const outside = await create(request, 'assets', { name: `Beyond horizon ${suffix}`, category_id: category.id, person_id: person.id, projected_yearly_growth: null })
  const none = await create(request, 'assets', { name: `No plan ${suffix}`, category_id: category.id, person_id: person.id, projected_yearly_growth: null })
  const now = new Date()
  const month = (offset: number) => { const date = new Date(now.getFullYear(), now.getMonth() + offset, 1); return `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}` }
  await create(request, 'data-points/batch', { items: [
    { asset_id: planned.id, year_month: month(0), value: 999 },
    { asset_id: planned.id, year_month: month(3), value: 700 },
    { asset_id: actualOnly.id, year_month: month(0), value: 100 },
    { asset_id: outside.id, year_month: month(0), value: 200 },
    { asset_id: outside.id, year_month: month(72), value: 400 },
    { asset_id: none.id, year_month: month(0), value: 300 },
  ] })
  const summary = await (await request.get(`/api/v1/summary?range=1y&person=${person.id}`)).json()
  expect(summary.current_total).toBe(100)
  const result = await (await request.get('/api/v1/projections?years=5&scenario=base')).json()
  const series = result.projection.series.find((item: { category_id: string }) => item.category_id === category.id)
  expect(series.available.slice(0, 3)).toEqual([false, false, true])
  expect(series.values.slice(0, 3)).toEqual([0, 0, 700])

  await page.goto('/monthly-update')
  await expect(page.getByRole('spinbutton', { name: new RegExp(`Value for ${plannedName}`) }).last()).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: new RegExp(`Value for ${actualOnly.name}`) }).last()).toBeVisible()
  await page.goto('/projections')
  await page.getByRole('button', { name: '5Y', exact: true }).click()
  const assumptions = page.locator('#assumptions-panel')
  const plannedRow = assumptions.getByText(plannedName, { exact: true }).locator('..')
  await expect(plannedRow).not.toContainText('Current wealth:')
  await expect(plannedRow.locator('..')).toContainText('Category defaults · Current wealth: excluded · Projections: included')
  await expect(plannedRow).toContainText(`Starts ${month(3)}`)
  const outsideRow = assumptions.getByText(outside.name, { exact: true }).locator('..')
  await expect(outsideRow).toContainText(`Starts ${month(72)} (outside the selected horizon)`)
  const noneRow = assumptions.getByText(none.name, { exact: true }).locator('..')
  await expect(noneRow).toContainText('No future planned entry')
  const actualRow = assumptions.getByText(actualOnly.name, { exact: true }).locator('..')
  await expect(actualRow).toContainText('Current wealth: included')
  await expect(actualRow).toContainText('Projections: excluded')
  await page.getByText('View projection chart data').click()
  const table = page.getByRole('table', { name: 'Historical and projected values for visible categories' })
  const headers = await table.getByRole('columnheader').allTextContents()
  const categoryColumn = headers.indexOf(categoryName)
  expect(categoryColumn).toBeGreaterThanOrEqual(0)
  for (const offset of [1, 2]) await expect(table.getByRole('row').filter({ hasText: month(offset) }).locator('td').nth(categoryColumn - 1)).toHaveText('—')
  await expect(table.getByRole('row').filter({ hasText: month(3) }).locator('td').nth(categoryColumn - 1)).toContainText('700,00')

  await page.goto('/admin')
  await page.getByRole('tab', { name: 'Categories' }).click()
  await page.getByRole('button', { name: `Edit category ${categoryName}` }).click()
  dialog = page.getByRole('dialog', { name: 'Edit Category' })
  await dialog.getByRole('switch', { name: 'Include in current wealth' }).click()
  await dialog.getByRole('switch', { name: 'Include in projections' }).click()
  await dialog.getByRole('button', { name: 'Save' }).click()
  await expect(dialog).toBeHidden()
  const changedSummary = await (await request.get(`/api/v1/summary?range=1y&person=${person.id}`)).json()
  expect(changedSummary.current_total).toBe(1599)
  const changedProjection = await (await request.get('/api/v1/projections?years=5&scenario=base')).json()
  const metadata = changedProjection.projection.asset_metadata.find((item: { asset_id: string }) => item.asset_id === planned.id)
  expect(metadata.effective_include_in_current_wealth).toBe(true)
  expect(metadata.effective_include_in_projections).toBe(false)
})


test('unavailable projection milestones are not shown as zero', async ({ page }) => {
  await page.route('**/api/v1/projections?*', async route => {
    const response = await route.fetch()
    const json = await response.json()
    json.projection.available = json.projection.months.map(() => false)
    for (const series of json.projection.series) series.available = json.projection.months.map(() => false)
    await route.fulfill({ response, json })
  })
  await page.goto('/projections')
  await expect(page.getByText('No projected values are available in this horizon.')).toBeVisible()
  const milestones = page.getByText('Projected Milestones', { exact: true }).locator('..')
  await expect(milestones.getByText('—').first()).toBeVisible()
  await expect(milestones.getByText('0,00', { exact: false })).toHaveCount(0)
  await page.unrouteAll({ behavior: 'wait' })
})


test('income forms do not offer wealth inclusion controls', async ({ page, request }) => {
  const suffix = Date.now()
  const person = await create(request, 'persons', { name: `Income inclusion person ${suffix}` })
  const category = await create(request, 'categories', { name: `Income inclusion category ${suffix}`, type: 'cash-inflow', projected_yearly_growth: 0, color: '#14b8a6' })
  await create(request, 'assets', { name: `Income inclusion source ${suffix}`, category_id: category.id, person_id: person.id, projected_yearly_growth: null })
  await page.goto('/admin')
  await page.getByRole('tab', { name: 'Categories' }).click()
  await page.getByRole('button', { name: `Edit category ${category.name}` }).click()
  let dialog = page.getByRole('dialog', { name: 'Edit Category' })
  await expect(dialog.getByRole('switch', { name: 'Include in current wealth' })).toHaveCount(0)
  await expect(dialog.getByText('Income is tracked separately on the Income page.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Cancel' }).click()
  await page.getByRole('tab', { name: 'Income', exact: false }).click()
  await page.getByRole('button', { name: `Edit asset Income inclusion source ${suffix}` }).click()
  dialog = page.getByRole('dialog', { name: 'Edit Income' })
  await expect(dialog.getByText('Advanced', { exact: true })).toBeVisible()
  await dialog.getByText('Advanced', { exact: true }).click()
  await expect(dialog.getByRole('checkbox', { name: 'Closed' })).toBeVisible()
  await expect(dialog.getByRole('group', { name: 'Current wealth' })).toHaveCount(0)
})
